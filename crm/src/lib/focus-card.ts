import { useEffect, useRef } from "react";
import { useSearchParams } from "react-router";

/**
 * Подводит к карточке, на которую указывает `?focus=<id>`, и подсвечивает её.
 *
 * Отличие от `?open=<id>` (см. `open-from-search.ts`) — в намерении. Поиск
 * отвечает на «найди мне вот это», и открыть карточку сразу правильно: человек
 * уже знает, что ему нужно. «Сегодня» отвечает на «что горит», и там карточка
 * — это пункт списка, а не пункт назначения: открывать её окном значит решать
 * за человека, что он собрался её править, хотя он мог просто посмотреть, где
 * она стоит и что рядом.
 *
 * Поэтому здесь только переход и подсветка. Она нужна, потому что раздел — это
 * список из полусотни строк, и без неё приходится заново глазами искать ту,
 * на которую только что нажали.
 *
 * Работает через DOM, а не через состояние: иначе признак «подсвечена» пришлось
 * бы протаскивать в каждую строку каждого списка, а списков шесть и все разные.
 */

/** Сколько живёт подсветка — ровно длительность `.crm-focused` в стилях. */
const RING_MS = 3600;

export function useFocusFromLink(ready: boolean): void {
  const [params, setParams] = useSearchParams();
  const wanted = params.get("focus");
  // Что уже подсвечивали: параметр убирается не мгновенно, и без отметки
  // эффект успевает сработать второй раз на том же идентификаторе.
  const handled = useRef<string | null>(null);

  useEffect(() => {
    if (!wanted || !ready || handled.current === wanted) return;

    const node = document.querySelector<HTMLElement>(
      `[data-card-id="${CSS.escape(wanted)}"]`,
    );
    // Карточки может не быть на экране: включён другой срез или доска вместо
    // списка. Тогда просто ничего не делаем — попробуем на следующем рендере.
    if (!node) return;

    handled.current = wanted;
    node.scrollIntoView({ block: "center", behavior: "smooth" });
    node.classList.add("crm-focused");

    /*
     * Таймер намеренно без очистки в возврате эффекта. Строкой ниже `setParams`
     * меняет адрес, эффект перезапускается — и очистка сняла бы класс в тот же
     * миг, когда он появился. Узел к моменту срабатывания может быть уже удалён
     * из документа; снятие класса с открепившегося узла безвредно.
     *
     * Класс снимается, а не остаётся висеть отработавшей анимацией: иначе
     * повторный переход к той же карточке ничего бы не показал.
     */
    setTimeout(() => node.classList.remove("crm-focused"), RING_MS);

    // Параметр убирается сразу: иначе подсветка возвращалась бы при каждом
    // обновлении списка.
    setParams({}, { replace: true });
  }, [wanted, ready, setParams]);
}
